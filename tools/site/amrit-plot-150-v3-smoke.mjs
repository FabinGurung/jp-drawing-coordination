import assert from 'node:assert/strict';import fs from 'node:fs';import crypto from 'node:crypto';
const p='public/data/projects/14-amrit-hardware-1/';
const j=JSON.parse(fs.readFileSync(p+'plot-150-owner-concept-v3.json','utf8'));
const source=JSON.parse(fs.readFileSync(p+'plot-150-pdf-trace-v1.json','utf8'));
const svg=fs.readFileSync(p+'plot-150-owner-concept-v3.svg','utf8');
const m=JSON.parse(svg.match(/<metadata id="jp-cad-model"[^>]*><!\[CDATA\[([\s\S]*?)\]\]><\/metadata>/)?.[1]||'null');
assert.deepEqual(m,j);assert.equal(j.edition.enumeration,'AAD-14-AMRIT-P150-V003');
assert.deepEqual(j.geometry.outer.vertices,source.geometry.outer.vertices);
assert.deepEqual(j.geometry.reservedUndergroundZones.find(x=>x.id==='UWT-01').rectMm,[3600,15550,5800,16850]);
const sha=crypto.createHash('sha256').update(svg).digest('hex');
assert.equal(fs.readFileSync(p+'snapshots/'+sha.slice(0,16)+'.svg','utf8'),svg);
console.log('PLOT150_HISTORICAL_V003_SOURCE_FROZEN_PASS '+sha);
