import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
const p='public/data/projects/14-amrit-hardware-1/';
const j=JSON.parse(fs.readFileSync(p+'plot-150-working.json','utf8'));
const baseline=JSON.parse(fs.readFileSync(p+'plot-150-pdf-trace-v1.json','utf8'));
const v2=JSON.parse(fs.readFileSync(p+'plot-150-owner-concept-v2.json','utf8'));
const svg=fs.readFileSync(p+'plot-150-working.svg','utf8');
const m=JSON.parse(svg.match(/<metadata id="jp-cad-model"[^>]*><!\[CDATA\[([\s\S]*?)\]\]><\/metadata>/)?.[1]||'null');
assert.deepEqual(m,j,'SVG metadata must be identical to published JSON for 3D');
assert.equal(j.edition.enumeration,'AAD-14-AMRIT-P150-V003');
assert.equal(j.edition.predecessor,'plot150-owner-front-only-concept-v2');
assert.deepEqual(j.geometry.outer.vertices,baseline.geometry.outer.vertices,'Never redraw legal/survey boundary for a tank');
assert.deepEqual(j.geometry.outer.edgeLabels,baseline.geometry.outer.edgeLabels);
assert.deepEqual(j.geometry.frontOnlySetback,v2.geometry.frontOnlySetback);
assert.deepEqual(j.geometry.house,v2.geometry.house);
assert.deepEqual(j.geometry.reservedUndergroundZones.slice(1),v2.geometry.reservedUndergroundZones.slice(1));
const tank=j.geometry.reservedUndergroundZones.find(z=>z.id==='UWT-01');
assert.deepEqual(tank.rectMm,[3600,15550,5800,16850]);
const bb=tank.rectMm, corners=[[bb[0],bb[1]],[bb[2],bb[1]],[bb[2],bb[3]],[bb[0],bb[3]]];
function inside(p,a){let c=false;for(let i=0,j=a.length-1;i<a.length;j=i++){if((a[i][1]>p[1])!==(a[j][1]>p[1]))c^=p[0]<(a[j][0]-a[i][0])*(p[1]-a[i][1])/(a[j][1]-a[i][1])+a[i][0];}return c;}
assert.ok(corners.every(c=>inside(c,j.geometry.outer.vertices)),'Tank must remain entirely inside original red boundary');
assert.ok(corners.every(c=>inside(c,j.geometry.buildablePolygonMm)),'Tank must remain inside drawing-only front setback area');
assert.ok(bb[1]>j.geometry.house.rectMm[3],'Water tank overlaps house');
assert.equal(tank.approval,'HOLD');
assert.equal(j.geometry.surveyVerified,false);
const sha=crypto.createHash('sha256').update(svg).digest('hex');
const prov=JSON.parse(fs.readFileSync(p+'plot-150-source-provenance.json','utf8'));
assert.equal(prov.sourceSha256,sha);
assert.equal(prov.aadEdition,'AAD-14-AMRIT-P150-V003');
assert.equal(fs.readFileSync(p+'snapshots/'+sha.slice(0,16)+'.svg','utf8'),svg);
assert.ok(fs.existsSync(p+'plot-150-owner-concept-v2.svg'));
console.log('PLOT150_A7_V003_GOOGLE_DOC_SOURCE_SVG_3D_TANK_INSIDE_ORIGINAL_BOUNDARY_PASS '+sha);
