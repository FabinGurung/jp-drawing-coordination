import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
const base='public/data/projects/14-amrit-hardware-1/';
const source=JSON.parse(fs.readFileSync(base+'plot-150-pdf-trace-v1.json','utf8'));
const current=JSON.parse(fs.readFileSync(base+'plot-150-working.json','utf8'));
const svg=fs.readFileSync(base+'plot-150-working.svg','utf8');
const provenance=JSON.parse(fs.readFileSync(base+'plot-150-source-provenance.json','utf8'));
assert.equal(current.schema,'jp-cad://site-plot-boundary/2.0');
assert.equal(current.project.plotNumber,'150');
assert.deepEqual(current.geometry.outer.vertices,source.geometry.outer.vertices);
assert.deepEqual(current.geometry.outer.edgeLabels,source.geometry.outer.edgeLabels);
assert.deepEqual(current.geometry.orientation,{leftBoundary:'NORTH',topBoundary:'EAST_REAR',rightBoundary:'SOUTH',bottomBoundary:'WEST_FRONT_ROAD',basis:'OWNER_INSTRUCTION_2026-11-20',geographicBearingVerified:false,frontEdgeIndex:2,northEdgeIndex:3,eastEdgeIndex:0,southEdgeIndex:1});
assert.equal(current.geometry.georeferenced,false);
assert.equal(current.geometry.surveyVerified,false);
assert.equal(current.geometry.frontOnlySetback.polygonMm.length,4);
assert.ok(current.geometry.frontOnlySetback.polygonMm.some(p=>p[0]===0&&p[1]===0));
assert.ok(current.geometry.frontOnlySetback.polygonMm.some(p=>p[0]===10326&&p[1]===4635));
assert.equal(current.geometry.house.floorAreaSqm,42.75);
assert.deepEqual(current.geometry.reservedUndergroundZones.map(z=>z.id),['UWT-01','ST-01','SP-01']);
assert.ok(current.geometry.reservedUndergroundZones.every(z=>z.approval==='HOLD'&&z.depthMm===null&&z.capacityL===null));
assert.equal(current.geometry.house.constructionApproved,false);
const model=JSON.parse(svg.match(/<metadata id="jp-cad-model"[^>]*><!\[CDATA\[([\s\S]*?)\]\]><\/metadata>/)?.[1]||'null');
assert.deepEqual(model,current,'2D and 3D must come from the same canonical SVG metadata');
const sha=crypto.createHash('sha256').update(svg).digest('hex');
assert.equal(provenance.sourceSha256,sha);
assert.equal(provenance.surveyVerified,false);
assert.equal(provenance.constructionApproved,false);
assert.ok(fs.existsSync(base+'snapshots/'+sha.slice(0,16)+'.svg'));
assert.equal(fs.readFileSync(base+'snapshots/'+sha.slice(0,16)+'.svg','utf8'),svg);
assert.ok(fs.existsSync('public/projects/14-amrit-hardware-1/plot/index.html'));
console.log('AMRIT_PLOT_150_OWNER_FRONT_ONLY_SVG_DOC_MODEL_3D_AND_SNAPSHOT_PASS',sha);
