import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
const root='public/data/projects/14-amrit-hardware-1/';
const current=JSON.parse(fs.readFileSync(root+'plot-150-working.json','utf8'));
const v4=JSON.parse(fs.readFileSync(root+'plot-150-owner-concept-v4.json','utf8'));
const original=JSON.parse(fs.readFileSync(root+'plot-150-pdf-trace-v1.json','utf8'));
const svg=fs.readFileSync(root+'plot-150-working.svg','utf8');
const embedded=JSON.parse(svg.match(/<metadata id="jp-cad-model"><!\[CDATA\[([\s\S]*?)\]\]><\/metadata>/)?.[1]||'null');
assert.deepEqual(embedded,current,'Canonical SVG JSON differs from 3D payload');
assert.equal(current.edition.enumeration,'AAD-14-AMRIT-P150-V005');
assert.equal(current.edition.predecessor,'plot150-two-bedroom-threejs-v4');
assert.deepEqual(current.geometry.outer.vertices,original.geometry.outer.vertices);
assert.deepEqual(current.geometry.outer.edgeLabels,original.geometry.outer.edgeLabels);
assert.deepEqual(current.geometry.house.polygonMm,v4.geometry.house.polygonMm);
assert.deepEqual(current.geometry.house.plan.frameMm,v4.geometry.house.plan.frameMm);
assert.deepEqual(current.geometry.house.plan.wallSegments,v4.geometry.house.plan.wallSegments);
assert.deepEqual(current.geometry.house.plan.doorOpenings,v4.geometry.house.plan.doorOpenings);
assert.deepEqual(current.geometry.house.plan.rooms.map(({fill,areaSqFtGross,...core})=>core),v4.geometry.house.plan.rooms.map(({fill,areaSqFtGross,...core})=>core));
assert.deepEqual(current.geometry.reservedUndergroundZones,[]);
assert.deepEqual(current.display.palette,['#000000','#ffffff']);
assert.equal(current.display.dimensionUnits,'feet-inches');
assert.equal(current.display.areaUnits,'sq ft');
assert.ok(svg.includes('hatch-kitchen')&&svg.includes('hatch-west'));
const graphics=svg.slice(svg.indexOf('</metadata>')+11);
assert.doesNotMatch(graphics,/\d+(?:\.\d+)?\s*m²|\d+(?:\.\d+)?\s*m(?![a-z])/,'Metric dimension in visible SVG');
for(const x of [...svg.matchAll(/#[0-9a-fA-F]{3,8}\b/g)])assert.ok(['#ffffff','#000000'].includes(x[0].toLowerCase()),'Non-monochrome SVG color '+x[0]);
const src=fs.readFileSync('src/plot150-three.mjs','utf8');
assert.match(src,/from 'three'/);assert.match(src,/export function mountPlot150Three/);assert.match(src,/hatchRoom/);assert.match(src,/plan\.wallSegments/);
for(const x of [...src.matchAll(/#[0-9a-fA-F]{3,8}\b/g)])assert.ok(['#ffffff','#000000'].includes(x[0].toLowerCase()),'Non-monochrome 3D material '+x[0]);
const area=Math.round(current.geometry.house.floorAreaSqm*10.76391041671*100)/100;
assert.equal(area,684.91);
const sha=crypto.createHash('sha256').update(svg).digest('hex');
const three=crypto.createHash('sha256').update(src).digest('hex');
const prov=JSON.parse(fs.readFileSync(root+'plot-150-source-provenance.json','utf8'));
assert.equal(prov.sourceSha256,sha);assert.equal(prov.threeJsSourceSha256,three);
assert.equal(fs.readFileSync(root+'snapshots/'+sha.slice(0,16)+'.svg','utf8'),svg);
assert.equal(fs.readFileSync(root+'snapshots/threejs-'+three.slice(0,16)+'.mjs','utf8'),src);
assert.match(fs.readFileSync('vite.config.ts','utf8'),/plot150-three\.v005\.js/);
const reader=fs.readFileSync('public/assets/js/plot-boundary-engine.mjs','utf8');
assert.match(reader,/const ftIn=/);assert.match(reader,/const sqFt=/);
assert.doesNotMatch(reader,/m²/);
const html=fs.readFileSync('public/projects/14-amrit-hardware-1/plot/index.html','utf8');
for(const x of [...html.matchAll(/#[0-9a-fA-F]{3,8}\b/g)])assert.ok(['#ffffff','#000000'].includes(x[0].toLowerCase()),'Non-monochrome page color '+x[0]);
console.log('PLOT150_V005_BLACKWHITE_HATCH_FEET_SQFT_THREEJS_SOURCE_AND_IMMUTABLE_V004_PASS',sha,three);
