import assert from 'node:assert/strict';
import fs from 'node:fs';
import {CHAPTERS,PROJECTS} from '../../public/assets/js/project-workspace-config.mjs';
import {takeoffRows,measure,dimensionsFor,miniPlanSvg,miniVolumeSvg,toDisplayPosition,METRES_TO_FEET} from '../../public/assets/js/cad-client-takeoff.mjs';
const read=p=>fs.readFileSync(p,'utf8');
const json=p=>JSON.parse(read(p));
const path0='public/data/projects/ashok-adhikari/';
const m=json(path0+'aad-building-v3-7-architectural-final.json');
const gf=json(path0+'aad-gf-model-v3-6-review.json'),ff=json(path0+'aad-ff-model-v3-6-review.json');
assert.deepEqual(CHAPTERS.map(x=>x[0]),['views','boq','packages','sources','more']);
assert.deepEqual(CHAPTERS.slice(2,4).map(x=>x[1]),['04','05']);
const rows=takeoffRows(m,{gf,ff});
const gfWalls=rows.filter(r=>r.floor==='gf'&&r.type==='wall'),gfDoors=rows.filter(r=>r.floor==='gf'&&r.type==='door'),gfWindows=rows.filter(r=>r.floor==='gf'&&r.type==='window');
assert.equal(gfWalls.length,gf.floorGraph.walls.length,'source graph walls preserved');
assert.equal(gfDoors.length,gf.floorGraph.openings.filter(x=>x.kind==='door').length);
assert.equal(gfWindows.length,gf.floorGraph.openings.filter(x=>x.kind==='window').length);
assert.ok(rows.length>100,'source-backed presentations and graph items expected');
assert.ok(rows.every(r=>r.key&&r.technical?.id&&r.technical?.source!==undefined),'full entity identity retained');
const wall=gfWalls[0],door=gfDoors[0];
assert.ok(wall.L>0&&wall.B>0&&wall.H>0&&wall.area>0&&wall.volume>0);
assert.ok(door.L>0&&door.H>0&&door.area>0);
assert.equal(door.B,null,'door has no invented breadth');
assert.equal(door.volume,null,'door has no invented volume');
assert.equal(measure(null,'m'),'—');
assert.equal(measure(1,'m'),'1.00 m');
assert.equal(measure(1,'ft'),'3.28 ft');
assert.equal(measure(1,'ft',2),'10.76 ft²');
assert.ok(Math.abs(METRES_TO_FEET-3.280839895)<.00000001);
assert.ok(dimensionsFor(wall,'ft').some(x=>x[1].endsWith('ft³')));
assert.ok(miniPlanSvg(wall).includes('role="img"'));
assert.ok(miniVolumeSvg(wall).includes('Isometric'));
assert.ok(toDisplayPosition(wall,'ft').includes('ft'));
const source=read('public/assets/js/project-workspace.mjs');
const css=read('public/assets/css/project-workspace.css');
assert.match(source,/cad-client-takeoff[.]mjs/);
assert.match(source,/pw-client-inspector/);
assert.match(source,/pw-client-takeoff/);
assert.match(source,/data-more-jump/);
assert.match(source,/panel==='more'/);
assert.match(source,/applyAshokClientFrame/);
assert.match(source,/Technical record/);
assert.match(css,/body\\[data-project-ui="ashok-client-v2"\\]/);
for(const old of ['#pw-axis-proof','#pw-dock','#pw-stage-shortcut','#pw-edit-direct','#pw-change-request','#pw-open-local-history'])
 assert.ok(css.includes(old),'legacy UI must be visually excluded: '+old);
const index=json('public/data/cad/memory-palace-level-1.v1.json');
const level=read('public/memory-wall/level-1/index.html');
assert.equal(index.chapters.length,6);
assert.ok(level.includes('Three')||level.includes('three levels'));
for(const n of ['1','2','3','4','5','6']){
 assert.ok(level.includes('id="chapter-'+n+'"'));
 assert.ok(level.includes('id="section-'+n+'"'));
 assert.ok(level.includes('id="poster-'+n+'"'));
}
assert.equal(PROJECTS['ashok-adhikari'].editions[0].id,'v3-7');
assert.equal(PROJECTS['ashok-adhikari'].editions[1].id,'v3-6');
console.log('CAD_CLIENT_FIRST_WORKSPACE_SMOKE_PASS',JSON.stringify({items:rows.length,gfWalls:gfWalls.length,gfDoors:gfDoors.length,gfWindows:gfWindows.length,chapters:CHAPTERS.map(x=>x[0]),memoryPosters:index.chapters.length}));
