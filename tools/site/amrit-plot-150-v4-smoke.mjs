assert.deepEqual(j.geometry.outer.edgeLabels,original.geometry.outer.edgeLabels);
assert.deepEqual(j.geometry.frontOnlySetback,v3.geometry.frontOnlySetback);
assert.deepEqual(j.geometry.reservedUndergroundZones,[]);
assert.equal(j.geometry.house.widthMm,6300);
assert.equal(j.geometry.house.depthMm,10100);
