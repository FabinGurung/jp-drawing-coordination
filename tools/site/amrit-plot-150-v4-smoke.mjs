for(const pt of j.geometry.house.polygonMm){assert.ok(inside(pt,j.geometry.outer.vertices),'house outside source plot');assert.ok(inside(pt,j.geometry.buildablePolygonMm),'house intrudes front-only setback');}
const f=j.geometry.house.plan.frameMm;
const fromLocal=(p)=>[f.origin[0]+p[0]*f.uAxis[0]+p[1]*f.vAxis[0],f.origin[1]+p[0]*f.uAxis[1]+p[1]*f.vAxis[1]];
for(const w of j.geometry.house.plan.wallSegments){assert.ok(inside(fromLocal(w.aLocalMm),j.geometry.outer.vertices));assert.ok(inside(fromLocal(w.bLocalMm),j.geometry.outer.vertices));}
