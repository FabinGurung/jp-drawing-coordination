import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
const base='public/data/projects/14-amrit-hardware-1/';
const j=JSON.parse(fs.readFileSync(base+'plot-150-working.json','utf8'));
