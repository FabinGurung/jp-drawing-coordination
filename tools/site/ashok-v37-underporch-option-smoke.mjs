import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createAADWorkspace} from '../../public/assets/js/aad-unified-workspace.mjs';
import {PROJECTS} from '../../public/assets/js/project-workspace-config.mjs';
import {validateEditionRegistries} from '../../public/assets/js/project-edition-contract.mjs';
const dir='public/data/projects/ashok-adhikari/';
const read=name=>JSON.parse(fs.readFileSync(dir+name,'utf8'));
const source=read('aad-building-v3-6-review.json');
const option=read('aad-building-v3-7-underporch-option.json');
const gf=read('aad-gf-model-v3-6-review.json'),ff=read('aad-ff-model-v3-6-review.json');
const eq=(a,b,label)=>assert.deepEqual(a,b,label);
validateEditionRegistries(PROJECTS);
const edition=PROJECTS['ashok-adhikari'].editions[0];
eq([edition.id,edition.kind,edition.predecessorId],['v3-7-option','design-option','v3-6'],'edition contract');
assert.equal(edition.manifest,'data/projects/ashok-adhikari/aad-building-v3-7-underporch-option.json');
assert.equal(option.release.previous,'v3-6-review');
assert.equal(option.restrictions.issueForConstruction,false);
assert.equal(option.restrictions.engineeringApproval,'HOLD');
assert.match(option.ownerSanitationOption20261117.status,/NOT_STRUCTURAL_OR_MUNICIPAL_APPROVAL/);
eq(option.presentation.outerBounds,source.presentation.outerBounds,'architectural footprint preserved');
eq(option.presentation.columnAxisGrid,source.presentation.columnAxisGrid,'provisional axes unchanged');
eq(option.presentation.sourceGeometryHash,source.presentation.sourceGeometryHash,'floor graph topology unchanged');
eq(option.presentation.roofAccess,source.presentation.roofAccess,'roof unchanged');
eq(option.presentation.stairBay,source.presentation.stairBay,'stairs unchanged');
eq(option.levels.map(l=>l.model),source.levels.map(l=>l.model),'floorgraph filenames preserved');
eq(option.levels.map(l=>l.sourceArea),source.levels.map(l=>l.sourceArea),'source floor areas not inflated');
eq(option.services.siteFrame.plinthRect,[1817,3126,9017,16764],'house remains in plot');
assert.equal(option.services.siteFrame.outsideWCRect,null,'retired external WC in option only');
const garage=gf.roomEnvelopes.find(r=>r.id==='GF-PARK');
const porch=source.presentation.elements.find(e=>e.id==='GF-PARK-FINISH');
assert.ok(garage&&porch);
eq(garage.bbox,[4290,762,7200,2962],'original garage floorgraph');
eq([porch.x,porch.z,porch.dx,porch.dz],[5.745,12.538,2.91,2.2],'3D garage centre');
const plotFrame=option.services.siteFrame;
const garageFrom3D=[Math.round((porch.x-porch.dx/2-plotFrame.originX)*1000),
 Math.round((plotFrame.originZ-(porch.z+porch.dz/2))*1000),
 Math.round((porch.x+porch.dx/2-plotFrame.originX)*1000),
 Math.round((plotFrame.originZ-(porch.z-porch.dz/2))*1000)];
eq(garageFrom3D,[6107,3126,9017,5326],'garage truly front-right');
eq(option.ownerSanitationOption20261117.gfParkingPlotRectMm,garageFrom3D,'proposal garage basis');
const tank=option.services.assets.find(a=>a.id==='SEPTIC');
assert.equal(option.services.assets.length,1,'only one sealed septic, no soak');
assert.ok(tank&&tank.type==='WATERTIGHT_SEPTIC_CONCEPT');
eq([tank.xMm,tank.yMm,tank.widthMm,tank.lengthMm],[7562,4226,2400,1100]);
const tankRect=[tank.xMm-tank.widthMm/2,tank.yMm-tank.lengthMm/2,tank.xMm+tank.widthMm/2,tank.yMm+tank.lengthMm/2];
eq(tankRect,option.ownerSanitationOption20261117.siteTankRectMm,'source proposal rectangle');
eq([tankRect[0]-garageFrom3D[0],garageFrom3D[2]-tankRect[2],
     tankRect[1]-garageFrom3D[1],garageFrom3D[3]-tankRect[3]],[255,255,550,550],'nominal small porch margin: HOLD');
assert.ok(tankRect[0]>plotFrame.plinthRect[0] && tankRect[2]<plotFrame.plinthRect[2] &&
          tankRect[1]>plotFrame.plinthRect[1] && tankRect[3]<plotFrame.plinthRect[3],'tank within house envelope, not in setbacks');
assert.equal(tank.internalLiquidM3,null,'no fictitious capacity certification');
assert.match(tank.dischargeStatus,/NO_EFFLUENT_PATH_DESIGNED/);
assert.deepEqual(option.services.routes,[],'all superseded sanitary plumbing runs suppressed');
const ids=new Set(option.presentation.elements.map(e=>e.id));
assert.equal(ids.size,option.presentation.elements.length,'no duplicate presentation IDs');
assert.ok(ids.has('MEP-SEPTIC-V37-CONCEPT')&&ids.has('MEP-SEPTIC-V37-ACCESS-HATCH'));
assert.ok(![...ids].some(x=>x.startsWith('EXT-WC')||x==='FIX-GF-EXT-PAN'||x==='MEP-SOAK'),'no old WC/soak representation');
assert.ok(![...ids].some(x=>x.startsWith('MEP-')&&!x.startsWith('MEP-SEPTIC-V37')),'no stale MEP graphics');
assert.ok(ids.has('FIX-GF-WC'),'original shared-bath WC retained');
assert.ok(ids.has('GF-PARK-FINISH'),'actual GF car porch retained');
const part=option.presentation.elements.find(x=>x.id==='MEP-SEPTIC-V37-CONCEPT');
eq([part.x,part.z,part.dx,part.dz],[5.745,12.538,2.4,1.1],'tank 3D local coordinates');
assert.equal(part.status.includes('HOLD'),true);
assert.ok(part.parts.length>=5,'3D tank conceptual volumetric pieces provided');
const baseAssembly=createAADWorkspace(source,{gf,ff}).snapshot().assembly;
const optAssembly=createAADWorkspace(option,{gf,ff}).snapshot().assembly;
assert.ok(optAssembly.elements.some(e=>e.id.endsWith(':MEP-SEPTIC-V37-CONCEPT')),'new tank in 2D/3D assembly');
assert.ok(optAssembly.elements.some(e=>e.id.endsWith(':MEP-SEPTIC-V37-ACCESS-HATCH')),'access marker shown');
assert.ok(!optAssembly.elements.some(e=>e.id.endsWith(':MEP-SOAK')),'no under-footprint soak');
assert.ok(optAssembly.elements.length>60,'substantial actual linked building assembly');
eq(optAssembly.area,baseAssembly.area,'same computed occupied architectural floor perimeter area');
assert.ok(option.reviewHolds.some(h=>h.code==='V3_7_NO_SOAK_OR_EFFLUENT_ROUTE'));
assert.ok(option.reviewHolds.some(h=>h.code==='V3_7_SEALED_SEPTIC_BELOW_PARKING_STRUCTURAL_HOLD'));
assert.equal(source.services.assets.length,2,'v3.6 original unchanged');
assert.ok(source.presentation.elements.some(e=>e.id==='MEP-SOAK'),'v3.6 historical source preserved');
const json=fs.readFileSync(dir+'aad-building-v3-7-underporch-option.json','utf8');
assert.ok(!/drive[.]google|docs[.]google|drive.?id|sandbox:|sediment:/i.test(json),'no private Drive/provider identifiers');
console.log('ASHOK_V37_OWNER_APPROVED_DESIGN_OPTION_PASS',JSON.stringify({model:option.release.version,siteTankRectMm:tankRect,porchRectMm:garageFrom3D,
structural:'HOLD',municipal:'HOLD',effluent:'NO_ROUTE',wc:'GF_SHARED',originalPreserved:true}));
