import assert from 'node:assert/strict';
import fs from 'node:fs';
const path='public/data/projects/14-amrit-hardware-1/plot-150-pdf-trace-v1.json';
const m=JSON.parse(fs.readFileSync(path,'utf8'));
assert.equal(m.schema,'jp-cad://site-plot-boundary/1.0');
assert.equal(m.project.plotNumber,'150');
assert.equal(m.edition.status,'SOURCE_REVIEW_NOT_SURVEYED');
assert.equal(m.geometry.georeferenced,false);
assert.equal(m.geometry.surveyVerified,false);
assert.equal(m.geometry.buildingGeometryIncluded,false);
assert.equal(m.geometry.visualization.heightIsSurveyed,false);
assert.equal(m.measurements.setbackInterpretation,'UNRESOLVED_DOUBLE_QUOTE_VS_DRAWN_WIDTH');
assert.equal(m.geometry.outer.vertices.length,4);
assert.equal(m.geometry.inner.vertices.length,4);
const polygonArea=pts=>Math.abs(pts.reduce((sum,p,i)=>sum+p[0]*pts[(i+1)%pts.length][1]-pts[(i+1)%pts.length][0]*p[1],0)/2)/1e6;
const feet=[21.5,41+10/12,37+2/12,58+1/12];
const length=(a,b)=>Math.hypot(a[0]-b[0],a[1]-b[1])/304.8;
const poly=m.geometry.outer.vertices;
feet.forEach((ft,i)=>assert.ok(Math.abs(length(poly[i],poly[(i+1)%4])-ft)<.06,`Plot boundary ${i} inconsistent with PDF label`));
assert.ok(Math.abs(polygonArea(poly)-125.73)<.05);
assert.ok(Math.abs(polygonArea(m.geometry.inner.vertices)-72.30)<.05);
assert.ok(fs.existsSync('public/projects/14-amrit-hardware-1/plot/index.html'));
assert.ok(fs.existsSync('public/assets/js/plot-boundary-engine.mjs'));
assert.ok(fs.existsSync('public/data/projects/14-amrit-hardware-1/plot-150-pdf-trace-v1.dxf'));
assert.ok(fs.existsSync('public/data/projects/14-amrit-hardware-1/plot-150-pdf-trace-v1.svg'));
console.log('Plot 150 PDF geometry smoke passed: four plot sides, planar area, source-status and site renderer.');
